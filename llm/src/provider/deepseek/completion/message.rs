//! Types shared across request, response, and streaming.

use serde::{Deserialize, Serialize};

/// Role of a message sender
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Role {
    /// The role of the messages author, in this case `system`.
    System,
    /// The role of the messages author, in this case `user`.
    User,
    /// The role of the messages author, in this case `assistant`.
    Assistant,
    /// The role of the messages author, in this case `tool`.
    Tool,
}

/// A message in the conversation
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Message {
    /// Role of the message sender
    pub role: Role,

    /// Content of the message.
    ///
    /// For assistant messages this field is required but can be null (e.g. when
    /// only `tool_calls` are present without text). The field is always
    /// serialized — when `None` it becomes `"content": null` on the wire.
    ///
    /// The Chat Completions API accepts a plain string or an array of
    /// typed parts (text, image_url); the untagged [`MessageContent`]
    /// models both. Responses carry string content, so the array form
    /// only appears in requests.
    #[serde(default)]
    pub content: Option<MessageContent>,

    /// An optional name for the participant
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,

    /// Reasoning content (for thinking mode, returned by the model)
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reasoning_content: Option<String>,

    /// (Beta) Set to true to force the model to start its answer by the content of
    /// the supplied prefix in this assistant message.
    /// Requires `base_url="https://api.deepseek.com/beta"`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub prefix: Option<bool>,

    /// Tool calls (for assistant messages with tool_calls finish_reason)
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tool_calls: Vec<ToolCall>,

    /// Tool call ID (for tool role messages)
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_call_id: Option<String>,
}

/// Message content: a plain string or an array of typed parts.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(untagged)]
pub enum MessageContent {
    /// Plain text content.
    Text(String),
    /// Structured content parts.
    Parts(Vec<ContentPart>),
}

impl MessageContent {
    /// Flatten to plain text if this is a string or text-only parts.
    /// Image parts contribute nothing.
    pub fn into_text(self) -> Option<String> {
        match self {
            MessageContent::Text(t) => Some(t),
            MessageContent::Parts(parts) => {
                let text: String = parts
                    .into_iter()
                    .filter_map(|p| match p {
                        ContentPart::Text { text } => Some(text),
                        ContentPart::ImageUrl { .. } => None,
                    })
                    .collect::<Vec<_>>()
                    .join("\n");
                if text.is_empty() { None } else { Some(text) }
            }
        }
    }
}

/// A typed content part inside a message.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum ContentPart {
    /// Text content.
    #[serde(rename = "text")]
    Text {
        /// The text.
        text: String,
    },
    /// An inline image, referenced by data URL.
    #[serde(rename = "image_url")]
    ImageUrl {
        /// The image URL (data URL for inline images).
        image_url: ImageUrl,
    },
}

/// The `image_url` object inside an image content part.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ImageUrl {
    /// The URL of the image.
    pub url: String,
}

/// A tool call generated by the model
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolCall {
    /// Unique ID for this tool call
    pub id: String,

    /// Type of tool call (always "function")
    #[serde(rename = "type")]
    pub call_type: String,

    /// Function call details
    pub function: FunctionCall,
}

/// Function call details
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionCall {
    /// Name of the function to call
    pub name: String,

    /// Arguments as a JSON value
    #[serde(
        serialize_with = "serialize_json_string",
        deserialize_with = "deserialize_json_string"
    )]
    pub arguments: serde_json::Value,
}

/// Serialize a JSON Value as a JSON string (API expects string-encoded JSON)
fn serialize_json_string<S>(value: &serde_json::Value, serializer: S) -> Result<S::Ok, S::Error>
where
    S: serde::Serializer,
{
    serializer.serialize_str(&value.to_string())
}

/// Deserialize a JSON string into a JSON Value (handles the case where API returns JSON string)
fn deserialize_json_string<'de, D>(deserializer: D) -> Result<serde_json::Value, D::Error>
where
    D: serde::Deserializer<'de>,
{
    use serde::de::Error;
    let s = String::deserialize(deserializer)?;
    serde_json::from_str(&s).map_err(D::Error::custom)
}
