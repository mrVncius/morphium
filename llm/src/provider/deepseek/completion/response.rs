//! Response types for the chat completion endpoint.

use derive_more::Display;
use serde::{Deserialize, Serialize};

use super::message::Message;

/// Chat completion response
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct ChatCompletionResponse {
    /// Unique identifier for the completion
    pub id: String,

    /// Object type (always "chat.completion")
    pub object: String,

    /// Unix timestamp of creation
    pub created: u64,

    /// Model used for the completion
    pub model: String,

    /// System fingerprint (for tracking backend configuration)
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub system_fingerprint: Option<String>,

    /// List of completion choices
    pub choices: Vec<Choice>,

    /// Token usage statistics
    pub usage: Usage,
}

/// A completion choice
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct Choice {
    /// Index of the choice
    pub index: u32,

    /// The generated message
    pub message: Message,

    /// Reason why the generation stopped
    #[serde(rename = "finish_reason")]
    pub finish_reason: FinishReason,

    /// Log probabilities for tokens (if requested)
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub logprobs: Option<LogProbs>,
}

/// Reason why the generation finished
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Display)]
#[serde(rename_all = "snake_case")]
pub enum FinishReason {
    /// Model completed the message naturally
    #[display("stop")]
    Stop,
    /// Model called one or more tools
    #[display("tool_calls")]
    ToolCalls,
    /// Maximum token limit reached
    #[display("length")]
    Length,
    /// Content filtered
    #[display("content_filter")]
    ContentFilter,
    /// Request interrupted due to insufficient system resources
    #[display("insufficient_system_resource")]
    InsufficientSystemResource,
}

/// Log probabilities for tokens
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct LogProbs {
    /// List of message content token log probability information.
    /// Can be null if no logprobs are available for content tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub content: Option<Vec<LogProbToken>>,

    /// List of reasoning content token log probability information
    /// (for thinking mode only)
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reasoning_content: Option<Vec<LogProbToken>>,
}

/// Log probability information for a single token
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct LogProbToken {
    /// Token string
    pub token: String,

    /// Log probability of the token
    pub logprob: f64,

    /// UTF-8 byte representation of the token (null if no bytes representation)
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub bytes: Option<Vec<u32>>,

    /// List of alternative tokens and their logprobs (if top_logprobs > 0)
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub top_logprobs: Vec<TopLogProb>,
}

/// Top log probability alternative
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct TopLogProb {
    /// Token string
    pub token: String,

    /// Log probability
    pub logprob: f64,

    /// UTF-8 byte representation of the token (null if no bytes representation)
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub bytes: Option<Vec<u32>>,
}

/// Token usage statistics
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct Usage {
    /// Tokens in the prompt
    #[serde(rename = "prompt_tokens")]
    pub prompt_tokens: u32,

    /// Tokens in the completion
    #[serde(rename = "completion_tokens")]
    pub completion_tokens: u32,

    /// Total tokens (prompt + completion)
    #[serde(rename = "total_tokens")]
    pub total_tokens: u32,

    /// Tokens in the prompt that hit the context cache
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub prompt_cache_hit_tokens: Option<u32>,

    /// Tokens in the prompt that missed the context cache
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub prompt_cache_miss_tokens: Option<u32>,

    /// Breakdown of completion tokens
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub completion_tokens_details: Option<CompletionTokensDetails>,
}

/// Breakdown of tokens used in a completion
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct CompletionTokensDetails {
    /// Tokens generated by the model for reasoning
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reasoning_tokens: Option<u32>,
}
