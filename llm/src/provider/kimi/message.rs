//! Message, content-part, and tool-call types shared across the wire.
//!
//! Content parts carry `text`, `image_url`, or `video_url`; the media parts
//! accept either an object (`{"url": …}`) or a bare URL string. A `kimi-k3`
//! request may also carry a dynamic tool-loading message, modelled by
//! [`DynamicToolMessage`] and the [`InputMessage`] union.

use serde::{Deserialize, Serialize};

use super::tool::Tool;

/// Role of a message sender.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Role {
    /// System instructions.
    System,
    /// A user turn.
    User,
    /// A model turn (may carry tool calls).
    Assistant,
    /// A tool result.
    Tool,
}

/// A message in the conversation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Message {
    /// Role of the message sender.
    pub role: Role,

    /// Content, as a plain string or an array of typed parts.
    ///
    /// Serialized even when `None` (an assistant message with only tool
    /// calls) as `"content": null`.
    #[serde(default)]
    pub content: Option<MessageContent>,

    /// Optional name for the message sender.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,

    /// Reasoning content returned in thinking mode. Preserved across turns
    /// only when the model is configured for it (`thinking.keep: "all"`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reasoning_content: Option<String>,

    /// Tool calls emitted by the assistant.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tool_calls: Vec<ToolCall>,

    /// Tool call ID, required on a `tool` role message.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_call_id: Option<String>,

    /// Partial Mode: prefill an assistant output prefix (last assistant
    /// message only).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub partial: Option<bool>,
}

/// Message content: a plain string or an array of typed parts.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(untagged)]
pub enum MessageContent {
    /// Plain text content.
    Text(String),
    /// Structured content parts.
    Parts(Vec<ContentPart>),
}

impl MessageContent {
    /// Flatten to plain text if this is a string or text-only parts.
    ///
    /// Image and video parts contribute nothing.
    pub fn into_text(self) -> Option<String> {
        match self {
            MessageContent::Text(t) => Some(t),
            MessageContent::Parts(parts) => {
                let text: String = parts
                    .into_iter()
                    .filter_map(|p| match p {
                        ContentPart::Text { text } => Some(text),
                        ContentPart::ImageUrl { .. } | ContentPart::VideoUrl { .. } => None,
                    })
                    .collect::<Vec<_>>()
                    .join("\n");
                if text.is_empty() { None } else { Some(text) }
            }
        }
    }
}

/// A typed content part inside a message.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum ContentPart {
    /// Text content.
    #[serde(rename = "text")]
    Text {
        /// The text.
        text: String,
    },
    /// An inline image, referenced by data URL, remote URL, or `ms://` file id.
    #[serde(rename = "image_url")]
    ImageUrl {
        /// The image reference.
        image_url: MediaUrl,
    },
    /// An inline video, referenced by data URL, remote URL, or `ms://` file id.
    #[serde(rename = "video_url")]
    VideoUrl {
        /// The video reference.
        video_url: MediaUrl,
    },
}

/// An image or video reference.
///
/// The vendor accepts the object form (`{"url": …}`) or a bare URL string.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(untagged)]
pub enum MediaUrl {
    /// Object form.
    Object {
        /// Image or video content: a base64 data URL or an `ms://<file_id>`.
        url: String,
    },
    /// Bare URL string.
    Url(String),
}

/// A tool call generated by the model.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolCall {
    /// Unique ID for this tool call.
    pub id: String,

    /// Type of tool call (always `function`).
    #[serde(rename = "type")]
    pub call_type: String,

    /// Function call details.
    pub function: FunctionCall,
}

/// Function call details.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionCall {
    /// Name of the function to call.
    pub name: String,

    /// Arguments as a JSON value.
    #[serde(
        serialize_with = "serialize_json_string",
        deserialize_with = "deserialize_json_string"
    )]
    pub arguments: serde_json::Value,
}

/// Role of a dynamic tool-loading message (always `system`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum SystemRole {
    /// The `system` role.
    System,
}

/// A `kimi-k3` dynamic tool-loading message.
///
/// Takes the `system` role, declares the tools available from its position
/// onward, and omits `content`.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct DynamicToolMessage {
    /// Always `system`.
    pub role: SystemRole,

    /// Tools available from this message onward.
    pub tools: Vec<Tool>,
}

/// An entry in the request `messages` array.
///
/// `kimi-k3` accepts a [`DynamicToolMessage`] alongside the standard
/// [`Message`] in the same array.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(untagged)]
pub enum InputMessage {
    /// A dynamic tool-loading message (`kimi-k3`).
    DynamicTool(DynamicToolMessage),
    /// A standard message.
    Standard(Message),
}

impl From<Message> for InputMessage {
    fn from(message: Message) -> Self {
        Self::Standard(message)
    }
}

/// Serialize a JSON value as a JSON string (the API expects string-encoded JSON).
fn serialize_json_string<S>(value: &serde_json::Value, serializer: S) -> Result<S::Ok, S::Error>
where
    S: serde::Serializer,
{
    serializer.serialize_str(&value.to_string())
}

/// Deserialize `arguments` from either a JSON string or a JSON object.
///
/// The vendor documents a JSON string; both forms are accepted so a
/// compatible deployment cannot break the parse.
fn deserialize_json_string<'de, D>(deserializer: D) -> Result<serde_json::Value, D::Error>
where
    D: serde::Deserializer<'de>,
{
    use serde::de::Error;
    match serde_json::Value::deserialize(deserializer)? {
        serde_json::Value::String(s) => serde_json::from_str(&s).map_err(D::Error::custom),
        other => Ok(other),
    }
}
