//! Response types for the OpenAI Realtime API.
//!
//! Covers the response object produced by the server, the parameters used to
//! create one, its status and usage details, and the error types shared with
//! the event streams.
//!
//! See: <https://developers.openai.com/api/reference/resources/realtime>

use derive_more::Display;
use serde::{Deserialize, Serialize};

use super::message::ConversationItem;
use super::prompt::{Metadata, ResponsePrompt};
use super::session::{Modality, RealtimeAudioFormats, RealtimeReasoning, Voice};
use super::tool::{RealtimeToolChoiceConfig, RealtimeToolsConfigUnion};

/// A response generated by the Realtime API.
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct RealtimeResponse {
    /// The unique ID of the response.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub id: Option<String>,

    /// The audio output configuration the response used.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub audio: Option<RealtimeResponseCreateAudioOutput>,

    /// The ID of the conversation this response belongs to.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub conversation_id: Option<String>,

    /// The maximum number of output tokens, or the string `"inf"` for no
    /// limit.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_output_tokens: Option<ResponseMaxOutputTokens>,

    /// Metadata attached to the response.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub metadata: Option<Metadata>,

    /// Always `"realtime.response"`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub object: Option<String>,

    /// The output items generated by the response.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub output: Vec<ConversationItem>,

    /// The modalities the response may output: `"text"` or `"audio"`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub output_modalities: Option<Vec<Modality>>,

    /// The status of the response: one of `"completed"`, `"cancelled"`,
    /// `"failed"`, `"incomplete"`, or `"in_progress"`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub status: Option<String>,

    /// Details about why the response has its status.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub status_details: Option<RealtimeResponseStatus>,

    /// Usage statistics for the response.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub usage: Option<RealtimeResponseUsage>,
}

/// Parameters for creating a response.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RealtimeResponseCreateParams {
    /// The audio output configuration to use.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub audio: Option<RealtimeResponseCreateAudioOutput>,

    /// Controls which conversation the response is added to: `"auto"`,
    /// `"none"`, or a conversation ID.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub conversation: Option<String>,

    /// The input items for the response.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub input: Vec<ConversationItem>,

    /// Instructions (system message) for the model.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub instructions: Option<String>,

    /// The maximum number of output tokens, or the string `"inf"` for no
    /// limit.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_output_tokens: Option<ResponseMaxOutputTokens>,

    /// Metadata to attach to the response.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub metadata: Option<Metadata>,

    /// The modalities the response may output: `"text"` or `"audio"`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub output_modalities: Option<Vec<Modality>>,

    /// Whether the model may call multiple tools in parallel.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parallel_tool_calls: Option<bool>,

    /// The prompt template to use for the response.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub prompt: Option<ResponsePrompt>,

    /// The reasoning configuration to use.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reasoning: Option<RealtimeReasoning>,

    /// How the model selects tools.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_choice: Option<RealtimeToolChoiceConfig>,

    /// The tools available to the model.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tools: Vec<RealtimeToolsConfigUnion>,
}

/// The audio output configuration for a response.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RealtimeResponseCreateAudioOutput {
    /// The output audio configuration.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub output: Option<RealtimeResponseOutputAudio>,
}

/// The format and voice of a response's audio output.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RealtimeResponseOutputAudio {
    /// The audio format the response outputs.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub format: Option<RealtimeAudioFormats>,

    /// The voice the model uses to respond.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub voice: Option<Voice>,
}

/// Details about the status of a response.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RealtimeResponseStatus {
    /// Error information for a `"failed"` response.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub error: Option<RealtimeResponseStatusError>,

    /// The reason the response ended with this status.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reason: Option<ResponseStatusReason>,

    /// The status of the response.
    #[serde(rename = "type", default, skip_serializing_if = "Option::is_none")]
    pub type_: Option<ResponseStatusKind>,
}

/// Error information for a failed response.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RealtimeResponseStatusError {
    /// An error code identifying the error type.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub code: Option<String>,

    /// A human-readable message describing the error.
    #[serde(rename = "type", default, skip_serializing_if = "Option::is_none")]
    pub type_: Option<String>,
}

/// The terminal status of a response.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Display)]
#[serde(rename_all = "snake_case")]
pub enum ResponseStatusKind {
    /// The response completed successfully.
    #[display("completed")]
    Completed,
    /// The response was cancelled.
    #[display("cancelled")]
    Cancelled,
    /// The response failed.
    #[display("failed")]
    Failed,
    /// The response is incomplete.
    #[display("incomplete")]
    Incomplete,
}

/// The reason a response ended without completing.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Display)]
#[serde(rename_all = "snake_case")]
pub enum ResponseStatusReason {
    /// A server VAD detected the end of the turn.
    #[display("turn_detected")]
    TurnDetected,
    /// The client cancelled the response.
    #[display("client_cancelled")]
    ClientCancelled,
    /// The maximum number of output tokens was reached.
    #[display("max_output_tokens")]
    MaxOutputTokens,
    /// The content filter blocked the response.
    #[display("content_filter")]
    ContentFilter,
}

/// Usage statistics for a response.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RealtimeResponseUsage {
    /// Details about the input tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub input_token_details: Option<RealtimeResponseUsageInputTokenDetails>,

    /// The number of input tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub input_tokens: Option<u64>,

    /// Details about the output tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub output_token_details: Option<RealtimeResponseUsageOutputTokenDetails>,

    /// The number of output tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub output_tokens: Option<u64>,

    /// The total number of tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub total_tokens: Option<u64>,
}

/// Details about the input tokens used by a response.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RealtimeResponseUsageInputTokenDetails {
    /// The number of audio input tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub audio_tokens: Option<u64>,

    /// The number of cached input tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cached_tokens: Option<u64>,

    /// Breakdown of the cached input tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cached_tokens_details: Option<CachedTokensDetails>,

    /// The number of image input tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub image_tokens: Option<u64>,

    /// The number of text input tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text_tokens: Option<u64>,
}

/// Breakdown of cached tokens by modality.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CachedTokensDetails {
    /// The number of cached audio tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub audio_tokens: Option<u64>,

    /// The number of cached image tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub image_tokens: Option<u64>,

    /// The number of cached text tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text_tokens: Option<u64>,
}

/// Details about the output tokens used by a response.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RealtimeResponseUsageOutputTokenDetails {
    /// The number of audio output tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub audio_tokens: Option<u64>,

    /// The number of text output tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text_tokens: Option<u64>,
}

/// An error returned by the Realtime API.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RealtimeError {
    /// A human-readable message describing the error.
    pub message: String,

    /// The type of the error.
    #[serde(rename = "type")]
    pub type_: String,

    /// An error code identifying the error type.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub code: Option<String>,

    /// The ID of the event that caused the error.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub event_id: Option<String>,

    /// The parameter that caused the error.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub param: Option<String>,
}

/// An error event returned by the Realtime API.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RealtimeErrorEvent {
    /// Details of the error.
    pub error: RealtimeError,

    /// The unique ID of the event.
    pub event_id: String,

    /// The type of the event. Always `"error"`.
    ///
    /// Defaulted and skipped when empty: [`RealtimeErrorEvent`] doubles as the
    /// payload of internally tagged unions (e.g.
    /// [`RealtimeTranslationServerEvent`](super::translation::RealtimeTranslationServerEvent)),
    /// whose tag consumes the `type` key before the payload is deserialized.
    #[serde(rename = "type", default, skip_serializing_if = "String::is_empty")]
    pub type_: String,
}

/// The maximum number of output tokens for a response.
///
/// Either a token count or the string `"inf"` for no limit.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Display)]
#[serde(untagged)]
#[display("{self:?}")]
pub enum ResponseMaxOutputTokens {
    /// No limit on the number of output tokens.
    Inf(String),
    /// A maximum number of output tokens.
    Count(u64),
}
