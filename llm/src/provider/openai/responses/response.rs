//! Response type for the Responses API.

use derive_more::Display;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;

use super::params::{MaxOutputTokens, Temperature, TopLogProbs, TopP};
use super::{OutputContent, OutputItem, ReasoningConfig, ResponsePrompt, ResponseTextConfig, Tool};

/// Response from the Responses API.
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct ResponsesResponse {
    /// The unique ID of the response.
    pub id: String,

    /// Always `"response"`.
    #[serde(rename = "object")]
    pub object_type: String,

    /// The Unix timestamp (in seconds) when the response was created.
    pub created_at: u64,

    /// One of: completed, failed, in_progress, cancelled, queued, incomplete.
    pub status: String,

    /// The Unix timestamp (in seconds) when the response was completed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub completed_at: Option<u64>,
    /// Error information if the response failed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub error: Option<ResponseError>,
    /// Details about why the response is incomplete.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub incomplete_details: Option<IncompleteDetails>,

    /// The model used to generate the response.
    pub model: String,

    /// The output items generated by the model.
    #[serde(default)]
    pub output: Vec<OutputItem>,

    /// SDK convenience: aggregated text from all output_text items.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub output_text: Option<String>,

    /// The instructions given to the model.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub instructions: Option<String>,
    /// The prompt template used.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub prompt: Option<ResponsePrompt>,
    /// The ID of the previous response in the conversation.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub previous_response_id: Option<String>,
    /// The conversation this response belongs to.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub conversation: Option<ConversationRef>,

    /// The tools available to the model.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tools: Vec<Tool>,
    /// How the model selects tools.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_choice: Option<serde_json::Value>,
    /// Whether parallel tool calls are allowed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parallel_tool_calls: Option<bool>,
    /// The maximum number of tool calls allowed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_tool_calls: Option<u32>,

    /// The sampling temperature used (0 to 2).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub temperature: Option<Temperature>,
    /// The top-p sampling parameter used (0 to 1).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub top_p: Option<TopP>,
    /// The number of top log probabilities returned (0 to 20).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub top_logprobs: Option<TopLogProbs>,

    /// The maximum number of output tokens (minimum 16).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_output_tokens: Option<MaxOutputTokens>,
    /// The text output format configuration.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text: Option<ResponseTextConfig>,
    /// The reasoning configuration.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reasoning: Option<ReasoningConfig>,
    /// Whether the response is stored.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub store: Option<bool>,
    /// Whether the response runs in the background.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub background: Option<bool>,
    /// The truncation strategy used.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub truncation: Option<String>,
    /// Safety identifier.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub safety_identifier: Option<String>,
    /// The end-user identifier.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub user: Option<String>,
    /// The service tier used.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub service_tier: Option<String>,
    /// Custom metadata attached to the response.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub metadata: Option<HashMap<String, String>>,
    /// The prompt cache key.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub prompt_cache_key: Option<String>,
    /// The prompt cache retention policy.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub prompt_cache_retention: Option<String>,
    /// Token usage statistics.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub usage: Option<Usage>,
}

/// Response error.
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct ResponseError {
    /// The error code.
    pub code: String,
    /// The error message.
    pub message: String,
}

/// Why the response is incomplete.
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct IncompleteDetails {
    /// The reason why the response is incomplete.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reason: Option<String>,
}

/// Conversation reference returned in the response.
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct ConversationRef {
    /// The unique ID of the conversation.
    pub id: String,
}

/// Token usage statistics.
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct Usage {
    /// The number of input tokens used.
    pub input_tokens: u32,
    /// Details about the input tokens (e.g., cached tokens).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub input_tokens_details: Option<InputTokensDetails>,
    /// The number of output tokens generated.
    pub output_tokens: u32,
    /// Details about the output tokens (e.g., reasoning tokens).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub output_tokens_details: Option<OutputTokensDetails>,
    /// The total number of tokens used.
    pub total_tokens: u32,
}

/// Details about input token usage.
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct InputTokensDetails {
    /// The number of cached input tokens.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cached_tokens: Option<u32>,
}

/// Details about output token usage.
#[derive(Debug, Clone, Serialize, Deserialize, Display)]
#[display("{self:?}")]
pub struct OutputTokensDetails {
    /// The number of reasoning tokens in the output.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reasoning_tokens: Option<u32>,
}

impl ResponsesResponse {
    /// Concatenated text from all `output_text` content parts.
    pub fn text(&self) -> String {
        self.output
            .iter()
            .filter_map(|item| match item {
                OutputItem::Message(msg) => Some(msg),
                _ => None,
            })
            .flat_map(|msg| &msg.content)
            .filter_map(|c| match c {
                OutputContent::OutputText { text, .. } => Some(text.as_str()),
                _ => None,
            })
            .collect::<Vec<_>>()
            .join("")
    }

    /// Returns true if the response completed successfully.
    pub fn is_completed(&self) -> bool {
        self.status == "completed"
    }

    /// Returns true if the response has an error.
    pub fn has_error(&self) -> bool {
        self.error.is_some()
    }
}
