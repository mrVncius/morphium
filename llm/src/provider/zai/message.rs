//! Message, content-part, and tool-call types shared across the wire.
//!
//! Z.AI's `arguments` is documented as a JSON object in the response schema
//! but OpenAI-compatible deployments return a JSON string; the serde helpers
//! accept either and always serialize a string.

use serde::{Deserialize, Serialize};

/// Role of a message sender.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Role {
    /// System instructions.
    System,
    /// A user turn.
    User,
    /// A model turn (may carry tool calls).
    Assistant,
    /// A tool result.
    Tool,
}

/// A message in the conversation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Message {
    /// Role of the message sender.
    pub role: Role,

    /// Content, as a plain string or an array of typed parts.
    ///
    /// Serialized even when `None` (an assistant message with only tool
    /// calls) as `"content": null`, which the API accepts.
    #[serde(default)]
    pub content: Option<MessageContent>,

    /// Reasoning content returned in thinking mode, or replayed when
    /// Preserved Thinking is enabled (`clear_thinking: false`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reasoning_content: Option<String>,

    /// Tool calls emitted by the assistant.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tool_calls: Vec<ToolCall>,

    /// Tool call ID, required on a `tool` role message.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_call_id: Option<String>,
}

/// Message content: a plain string or an array of typed parts.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(untagged)]
pub enum MessageContent {
    /// Plain text content.
    Text(String),
    /// Structured content parts.
    Parts(Vec<ContentPart>),
}

impl MessageContent {
    /// Flatten to plain text if this is a string or text-only parts.
    ///
    /// Image parts contribute nothing.
    pub fn into_text(self) -> Option<String> {
        match self {
            MessageContent::Text(t) => Some(t),
            MessageContent::Parts(parts) => {
                let text: String = parts
                    .into_iter()
                    .filter_map(|p| match p {
                        ContentPart::Text { text } => Some(text),
                        ContentPart::ImageUrl { .. } => None,
                    })
                    .collect::<Vec<_>>()
                    .join("\n");
                if text.is_empty() { None } else { Some(text) }
            }
        }
    }
}

/// A typed content part inside a message.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum ContentPart {
    /// Text content.
    #[serde(rename = "text")]
    Text {
        /// The text.
        text: String,
    },
    /// An inline image, referenced by data URL or remote URL.
    #[serde(rename = "image_url")]
    ImageUrl {
        /// The image wrapper.
        image_url: ImageUrl,
    },
}

/// The `image_url` object inside an image content part.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ImageUrl {
    /// The image URL or base64 data URL.
    pub url: String,
}

/// A tool call generated by the model.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolCall {
    /// Unique ID for this tool call.
    pub id: String,

    /// Type of tool call (always `function`).
    #[serde(rename = "type")]
    pub call_type: String,

    /// Function call details.
    pub function: FunctionCall,
}

/// Function call details.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionCall {
    /// Name of the function to call.
    pub name: String,

    /// Arguments as a JSON value.
    #[serde(
        serialize_with = "serialize_json_string",
        deserialize_with = "deserialize_json_string"
    )]
    pub arguments: serde_json::Value,
}

/// Serialize a JSON value as a JSON string (the API expects string-encoded JSON).
fn serialize_json_string<S>(value: &serde_json::Value, serializer: S) -> Result<S::Ok, S::Error>
where
    S: serde::Serializer,
{
    serializer.serialize_str(&value.to_string())
}

/// Deserialize `arguments` from either a JSON string or a JSON object.
///
/// The vendor documents an object; OpenAI-compatible deployments return a
/// string. Both are accepted.
fn deserialize_json_string<'de, D>(deserializer: D) -> Result<serde_json::Value, D::Error>
where
    D: serde::Deserializer<'de>,
{
    use serde::de::Error;
    match serde_json::Value::deserialize(deserializer)? {
        serde_json::Value::String(s) => serde_json::from_str(&s).map_err(D::Error::custom),
        other => Ok(other),
    }
}
